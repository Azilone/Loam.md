import AppKit
import CapturePlugin
import PluginKit
import UniformTypeIdentifiers

/// What the panel shows for one item before it is saved.
struct CaptureDraft: Identifiable, Equatable {
    let id = UUID()
    var content: CaptureContent
    /// A small picture: the image itself, or a PDF's first page.
    var preview: NSImage?
    /// One line under the title: "inkandswitch.com", "PNG · 1.2 MB", "412 characters".
    var detail: String

    var title: String { content.provisionalTitle() }
    var symbol: String {
        switch content.kind {
        case .link: "link"
        case .image: "photo"
        case .pdf: "doc.richtext"
        case .text: "text.alignleft"
        case .file: "doc"
        }
    }

    static func == (left: CaptureDraft, right: CaptureDraft) -> Bool { left.id == right.id }
}

/// Turns the clipboard into drafts, the richest form first: files, a picture, a PDF, a link, text. Password managers
/// mark what they copy as concealed or transient: that is never read.
enum PasteboardReader {
    enum Reading: Equatable {
        case items([CaptureDraft])
        /// Nothing, or what was there was refused (its first type, for the message).
        case empty
        case unsupported(String)
    }

    static let concealed: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    @MainActor
    static func read(_ pasteboard: NSPasteboard = .general) -> Reading {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !types.isEmpty else { return .empty }
        if !types.isDisjoint(with: concealed) { return .empty }

        // 1. Files copied in Finder.
        let urls = (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if !urls.isEmpty {
            let drafts = urls.compactMap(fileDraft)
            return drafts.isEmpty ? .unsupported("folder") : .items(drafts)
        }
        // 2. A picture (a screenshot copied with ⌃⇧⌘4, "Copy Image" in a browser).
        for (type, ext) in [(NSPasteboard.PasteboardType.png, "png"), (.init("public.jpeg"), "jpg"), (.init("public.heic"), "heic"), (.tiff, "tiff")] {
            guard let data = pasteboard.data(forType: type) else { continue }
            let (bytes, finalExt) = ext == "tiff" ? (NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) ?? data, "png") : (data, ext)
            return .items([CaptureDraft(
                content: .file(name: "Image.\(finalExt)", contents: .data(bytes)),
                preview: NSImage(data: data), detail: "\(finalExt.uppercased()) · \(size(bytes.count))"
            )])
        }
        // 3. A PDF as data.
        if let data = pasteboard.data(forType: .pdf) {
            return .items([CaptureDraft(content: .file(name: "Document.pdf", contents: .data(data)),
                                        preview: PDFPreview.firstPage(data), detail: "PDF · \(size(data.count))")])
        }
        // 4. A link: "Copy Link" gives a URL and often its title.
        let string = pasteboard.string(forType: .string) ?? ""
        let urlString = pasteboard.string(forType: .URL) ?? CaptureIdentity.singleURL(in: string)
        if let urlString, CaptureIdentity.canonicalURL(urlString) != nil {
            let title = pasteboard.string(forType: .init("public.url-name"))
            return .items([CaptureDraft(content: .link(url: urlString, title: title), preview: nil,
                                        detail: URL(string: urlString)?.host ?? urlString)])
        }
        // 5. Text (rich text and HTML are taken as their plain text).
        if !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .items([CaptureDraft(content: .text(string), preview: nil, detail: "\(string.count) characters")])
        }
        return .unsupported(pasteboard.types?.first?.rawValue ?? "unknown")
    }

    static func fileDraft(_ url: URL) -> CaptureDraft? {
        var isFolder: ObjCBool = false
        guard FileManager.default.fileExists(atPath: url.path, isDirectory: &isFolder), !isFolder.boolValue else { return nil }
        let bytes = (try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0
        let content = CaptureContent.file(name: url.lastPathComponent, contents: .file(url))
        let preview: NSImage? = switch content.kind {
        case .image: NSImage(contentsOf: url)
        case .pdf: (try? Data(contentsOf: url)).flatMap(PDFPreview.firstPage)
        default: NSWorkspace.shared.icon(forFile: url.path)
        }
        let kind = UTType(filenameExtension: url.pathExtension)?.localizedDescription ?? url.pathExtension.uppercased()
        return CaptureDraft(content: content, preview: preview, detail: "\(kind) · \(size(bytes))")
    }

    static func size(_ bytes: Int) -> String {
        ByteCountFormatter.string(fromByteCount: Int64(bytes), countStyle: .file)
    }
}
