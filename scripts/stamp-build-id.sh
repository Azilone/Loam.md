#!/usr/bin/env bash
# Writes the runtime build id into Sources/PluginKit/PluginRuntimeBuildID.swift, or puts the committed "dev" back.
#
#   stamp-build-id.sh            stamps and prints the id
#   stamp-build-id.sh --print    prints the id without writing
#   stamp-build-id.sh --restore  writes "dev" back
#
# The id is the short git revision plus a hash of everything a plugin compiles against: the sources and manifests
# of the root package and of App/, the resolved dependencies, and `swift --version`. Two builds of the same sources
# with the same compiler get the same id, so the app and a plugin built by another script from the same checkout
# match, and any change to the runtime makes old plugins "built for another version". Callers stamp, build, and
# restore in a trap, so the file is never committed stamped.
set -euo pipefail
cd "$(dirname "$0")/.."

file="Sources/PluginKit/PluginRuntimeBuildID.swift"

write() {
  local content
  content="// Generated by scripts/stamp-build-id.sh during stamped builds; committed as \"dev\". Do not edit.
@_alwaysEmitIntoClient
public var _pluginRuntimeBuildID: String { \"$1\" }"
  # Only rewrite on change, so an unchanged id does not rebuild the runtime.
  if [ "$(cat "$file" 2>/dev/null)" != "$content" ]; then
    printf '%s\n' "$content" > "$file"
  fi
}

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum | cut -c1-64; else shasum -a 256 | cut -c1-64; fi
}

compute() {
  local revision sources
  revision="$(git rev-parse --short=10 HEAD 2>/dev/null || echo nogit)"
  sources="$(
    {
      find Sources App/Sources -type f -name '*.swift' ! -path "$file"
      ls Package.swift Package.resolved App/Package.swift App/Package.resolved 2>/dev/null
    } | LC_ALL=C sort | while read -r path; do printf '%s %s\n' "$path" "$(sha256 < "$path")"; done
  )"
  local hash
  hash="$( { printf '%s\n' "$sources"; swift --version 2>&1 | head -1; } | sha256 | cut -c1-12)"
  echo "$revision-$hash"
}

case "${1:-}" in
  --restore) write dev ;;
  --print) compute ;;
  "") id="$(compute)"; write "$id"; echo "$id" ;;
  *) echo "usage: $0 [--print|--restore]" >&2; exit 2 ;;
esac
