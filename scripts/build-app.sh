#!/usr/bin/env bash
# Builds the macOS app bundle at App/build/Loam.app (macOS only). Usage: build-app.sh [debug|release]
# LOAM_SWIFT_FLAGS adds flags to every swift build, e.g. "-Xswiftc -DLOAM_AGENT_BRIDGE" for the agent debug channel in
# a release build (a debug build has it already; see docs/AGENT-TESTING.md).
#
#   Contents/MacOS/Loam                         the executable (App/Executable, product Loam)
#   Contents/Helpers/loam                       the command line (CLI/), on the same runtime, rpath ../Frameworks
#   Contents/Frameworks/libLoamRuntime.dylib    PluginKit, the kernel, the logic plugins
#   Contents/Frameworks/libLoamUIRuntime.dylib  PluginKitUI, the shell, the UI plugins
#   Contents/Resources/SDK/loam/                the stamped sources plugins build against (`loam plugin build`)
#
# Third-party plugins link the two libraries, so the process holds one copy of each type. The SDK snapshot is stamped
# with the runtime build id (scripts/stamp-build-id.sh); the build is checked for duplicated types (scripts/check-single-copy.sh), and
# signed (Apple Development certificate, else ad hoc): the libraries first, then the app with App/Loam.entitlements.
set -euo pipefail
[ -n "${LOAM_BUILD_LOCKED:-}" ] || LOAM_LOCK_LANE=app exec "$(dirname "$0")/build-lock.sh" "$0" "$@"
cd "$(dirname "$0")/.."
root="$PWD"

config="${1:-release}"
# The version (VERSION, or LOAM_VERSION) and the build number (the commit count, or LOAM_BUILD): an update is a
# higher build number. Only a release (LOAM_RELEASE=1, scripts/release.sh) carries the update feed and its public
# key, so a development build never replaces itself with a download.
version="${LOAM_VERSION:-$(cat "$root/VERSION")}"
build_number="${LOAM_BUILD:-$(git -C "$root" rev-list --count HEAD 2>/dev/null || echo 1)}"
update_keys=""
if [ "${LOAM_RELEASE:-0}" = 1 ]; then
  update_keys="    <key>LoamUpdateFeed</key><string>${LOAM_UPDATE_FEED:-https://raw.githubusercontent.com/Azilone/loam-releases/main}</string>
    <key>LoamUpdatePublicKey</key><string>$(tr -d '[:space:]' < "$root/App/Resources/update-public-key.txt")</string>
    <key>LoamAnalyticsURL</key><string>${LOAM_ANALYTICS_URL:-https://pulse.personalize.design/api/p}</string>
    <key>LoamAnalyticsWebsiteID</key><string>${LOAM_ANALYTICS_WEBSITE_ID:-2bc5e2bb-40d7-4d22-8fd0-a1047881fc0d}</string>"
fi
# The checkout itself is stamped only for a release. On macOS the loader never compares build ids (the ABI is
# stable; docs/PLUGIN-LOADING.md), and stamping rewrites a PluginKit file, so every later build of this checkout
# recompiled the whole runtime. A development app runs as "dev".
if [ "${LOAM_RELEASE:-0}" = 1 ]; then
  trap '"$root/scripts/stamp-build-id.sh" --restore' EXIT
  echo "Runtime build id: $(./scripts/stamp-build-id.sh)"
fi

# The SDK: a snapshot of what a plugin compiles against, carrying this build's id in its own copy of
# PluginRuntimeBuildID.swift. The folder keeps the package identity, loam; App/ is its UI package.
sdk_stage="$(mktemp -d)/loam"
mkdir -p "$sdk_stage/App"
cp Package.swift Package.resolved "$sdk_stage/"
cp App/Package.swift App/Package.resolved "$sdk_stage/App/"
rsync -a --exclude .DS_Store Sources "$sdk_stage/"
rsync -a --exclude .DS_Store App/Sources "$sdk_stage/App/"
# A debug build's SDK stays "dev": hashing every source takes seconds, and macOS never compares the id.
build_id=dev
[ "$config" = debug ] || build_id="$(./scripts/stamp-build-id.sh --print)"
printf '%s\n' "// Generated by scripts/stamp-build-id.sh during stamped builds; committed as \"dev\". Do not edit." \
  "@_alwaysEmitIntoClient" "public var _pluginRuntimeBuildID: String { \"$build_id\" }" \
  > "$sdk_stage/Sources/PluginKit/PluginRuntimeBuildID.swift"
echo "SDK build id: $build_id"

# shellcheck disable=SC2086
swift build -c "$config" ${LOAM_SWIFT_FLAGS:-} --package-path CLI --product loam
cli_bin="$(swift build -c "$config" --package-path CLI --show-bin-path)"

cd App
# shellcheck disable=SC2086
swift build -c "$config" ${LOAM_SWIFT_FLAGS:-} --package-path Executable --product Loam
bin="$(swift build -c "$config" --package-path Executable --show-bin-path)"

app="build/Loam.app"
libraries=(libLoamRuntime.dylib libLoamUIRuntime.dylib)
rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Helpers" "$app/Contents/Frameworks" "$app/Contents/Resources"
cp "$bin/Loam" "$app/Contents/MacOS/Loam"
cp "$root/App/Resources/Loam.icns" "$root/App/Resources/LoamBlue.icns" "$app/Contents/Resources/"
cp "$root/LICENSE" "$root/THIRD_PARTY_NOTICES.md" "$app/Contents/Resources/"
cp "$root/scripts/install-dependencies.command" "$app/Contents/Resources/"
chmod +x "$app/Contents/Resources/install-dependencies.command"
for strings in "$root"/App/Resources/*.lproj; do cp -R "$strings" "$app/Contents/Resources/"; done
# The demo vault a new, empty vault starts from (AppModel.seedDemoVault).
cp -R "$root/App/Resources/DemoVault" "$app/Contents/Resources/DemoVault"
# Loam's own symbols (LoamSymbol), as the app's asset catalog. Without Xcode's actool they fall back to SF Symbols. The output path is absolute: actool hands the work
# to a daemon that may have started in another folder, and resolves a relative path there.
# Compiled once into build/AssetsCache and copied from there until an asset changes (actool takes ~10 s).
if xcrun --find actool >/dev/null 2>&1; then
  assets=("$root/App/Resources/Symbols.xcassets" "$root/App/Resources/Loam.icon")
  cache="$PWD/build/AssetsCache"
  if [ ! -f "$cache/Assets.car" ] || [ -n "$(find "${assets[@]}" -newer "$cache/Assets.car" -print -quit)" ]; then
    rm -rf "$cache" && mkdir -p "$cache"
    # Loam.icon is the app icon made in Icon Composer: light and dark appearances, in the same Assets.car.
    xcrun actool "${assets[@]}" \
      --app-icon Loam --compile "$cache" --platform macosx \
      --minimum-deployment-target 26.0 --output-format human-readable-text --output-partial-info-plist "$(mktemp)" >/dev/null
  fi
  cp -R "$cache/." "$app/Contents/Resources/"
fi
cp "$cli_bin/loam" "$app/Contents/Helpers/loam"
mkdir -p "$app/Contents/Resources/SDK"
mv "$sdk_stage" "$app/Contents/Resources/SDK/loam"
rmdir "$(dirname "$sdk_stage")"
for library in "${libraries[@]}"; do cp "$bin/$library" "$app/Contents/Frameworks/$library"; done
# The modules' resources (Pele's script for DiagramsUI), where their code looks first.
for resources in "$bin"/*.bundle; do [ -d "$resources" ] && cp -R "$resources" "$app/Contents/Resources/"; done

# Drop the rpaths into the build folder, so the bundle never loads a library from there, and point the executable at
# Contents/Frameworks. The libraries keep @loader_path, which finds each other there.
delete_absolute_rpaths() {
  otool -l "$1" | awk '/LC_RPATH/ {getline; getline; print $2}' | while read -r rpath; do
    case "$rpath" in /*) install_name_tool -delete_rpath "$rpath" "$1" 2>/dev/null ;; esac
  done
}
# `loam` is built in CLI/ (its own runtime build, from the same stamped sources) and runs on the bundle's runtime.
for executable in MacOS/Loam Helpers/loam; do
  delete_absolute_rpaths "$app/Contents/$executable"
  install_name_tool -add_rpath "@executable_path/../Frameworks" "$app/Contents/$executable" 2>/dev/null
done
for library in "${libraries[@]}"; do delete_absolute_rpaths "$app/Contents/Frameworks/$library"; done

# Release only (~10 s): a type compiled into two images comes from the package graph, which `make app` checks.
[ "$config" = debug ] || "$root/scripts/check-single-copy.sh" "$app/Contents/MacOS/Loam" "$app/Contents/Helpers/loam" \
  "$app/Contents/Frameworks/libLoamRuntime.dylib" "$app/Contents/Frameworks/libLoamUIRuntime.dylib"

# A debug build carries its worktree (or branch) in its name, so the Dock and menu bar tell the builds apart.
display_name="Loam" short_name="Loam" build_label=""
if [ "$config" = debug ]; then
  case "$root" in */.claude/worktrees/*) label="${root##*/}" ;; *) label="$(git -C "$root" branch --show-current 2>/dev/null || echo dev)" ;; esac
  display_name="Loam [$label]" short_name="Loam-$label"
  build_label="    <key>LoamBuildLabel</key><string>$label</string>"
fi
cat > "$app/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>$short_name</string>
    <key>CFBundleDisplayName</key><string>$display_name</string>
    <key>CFBundleIdentifier</key><string>com.azilone.loam</string>
    <key>CFBundleExecutable</key><string>Loam</string>
    <key>CFBundleIconFile</key><string>Loam</string>
    <key>CFBundleIconName</key><string>Loam</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>$version</string>
    <key>CFBundleVersion</key><string>$build_number</string>
    <key>LSMinimumSystemVersion</key><string>26.0</string>
    <key>NSPrincipalClass</key><string>NSApplication</string>
    <key>NSHighResolutionCapable</key><true/>
    <key>CFBundleDevelopmentRegion</key><string>en</string>
    <key>CFBundleLocalizations</key><array><string>en</string><string>fr</string><string>zh-Hans</string><string>es</string><string>ja</string><string>ko</string><string>ar</string><string>it</string><string>nl</string><string>de</string><string>hi</string></array>
    <key>NSMicrophoneUsageDescription</key><string>Loam records your microphone when you record a meeting or a voice note.</string>
    <key>NSAudioCaptureUsageDescription</key><string>Loam records the Mac's sound during a call, so the other participants are in the transcript, without a bot.</string>
$update_keys
$build_label
</dict>
</plist>
PLIST

# Inside out: the libraries, then the app (which seals them). With the Mac's "Apple Development" certificate when
# there is one (LOAM_SIGN_IDENTITY picks another), else ad hoc. An ad-hoc signature changes with every build, so the
# Keychain asks for the login password again on each start to read the Meetings keys; a certificate's signature stays
# the same app from one build to the next. A Developer ID and the hardened runtime (--options runtime) come with
# notarization, where the entitlement matters.
identity="${LOAM_SIGN_IDENTITY:-$(security find-identity -v -p codesigning 2>/dev/null | sed -n 's/.*"\(Apple Development: [^"]*\)".*/\1/p' | head -1)}"
identity="${identity:--}"
for library in "${libraries[@]}"; do codesign --force --sign "$identity" "$app/Contents/Frameworks/$library" >/dev/null 2>&1; done
codesign --force --sign "$identity" "$app/Contents/Helpers/loam" >/dev/null 2>&1
codesign --force --sign "$identity" --entitlements Loam.entitlements "$app" >/dev/null 2>&1
codesign --verify --strict "$app"
echo "SDK: $(du -sh "$app/Contents/Resources/SDK" | cut -f1) in Contents/Resources/SDK/loam"
echo "Built $(pwd)/$app"
echo "To use its \`loam\`: ln -s \"/Applications/Loam.app/Contents/Helpers/loam\" /usr/local/bin/loam (once installed)"
